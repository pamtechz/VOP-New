import { randomUUID } from 'node:crypto';

const base='https://sandbox.momodeveloper.mtn.com';
const subscriptionKey=String(process.env.MTN_MOMO_SUBSCRIPTION_KEY||'').trim();
const callbackUrl=String(process.env.MTN_MOMO_CALLBACK_URL||'https://vopafrica.vercel.app/api/payments/webhooks/mtn-momo').trim();

if(!subscriptionKey){
  console.error('MTN_MOMO_SUBSCRIPTION_KEY is required. Copy the Collections primary subscription key from the MTN MoMo developer portal into your local environment.');
  process.exit(1);
}

let callbackHost='';
try{
  callbackHost=new URL(callbackUrl).hostname;
}catch{
  console.error('MTN_MOMO_CALLBACK_URL must be a valid absolute URL.');
  process.exit(1);
}
if(!callbackHost){
  console.error('MTN_MOMO_CALLBACK_URL must contain a hostname.');
  process.exit(1);
}

const apiUser=randomUUID();
const common={'Ocp-Apim-Subscription-Key':subscriptionKey};

async function jsonOrText(response){
  const text=await response.text();
  if(!text)return {};
  try{return JSON.parse(text);}catch{return {message:text};}
}

const createUser=await fetch(base+'/v1_0/apiuser',{
  method:'POST',
  headers:{...common,'X-Reference-Id':apiUser,'Content-Type':'application/json'},
  body:JSON.stringify({providerCallbackHost:callbackHost}),
});
if(!createUser.ok){
  const body=await jsonOrText(createUser);
  console.error('MTN sandbox API user creation failed:',createUser.status,body.message||body.code||'Unknown provider error');
  process.exit(1);
}

const createKey=await fetch(base+'/v1_0/apiuser/'+encodeURIComponent(apiUser)+'/apikey',{
  method:'POST',
  headers:{...common,'Content-Type':'application/json'},
});
const keyBody=await jsonOrText(createKey);
const apiKey=String(keyBody.apiKey||keyBody.api_key||'').trim();
if(!createKey.ok||!apiKey){
  console.error('MTN sandbox API key generation failed:',createKey.status,keyBody.message||keyBody.code||'API key missing from response');
  process.exit(1);
}

console.log('');
console.log('MTN MoMo sandbox credentials generated successfully.');
console.log('The API key is generated by the sandbox provisioning API; it is not displayed in the portal.');
console.log('');
console.log('MTN_MOMO_API_USER='+apiUser);
console.log('MTN_MOMO_API_KEY='+apiKey);
console.log('MTN_MOMO_ENVIRONMENT=sandbox');
console.log('MTN_MOMO_TARGET_ENVIRONMENT=sandbox');
console.log('MTN_MOMO_CALLBACK_URL='+callbackUrl);
console.log('');
console.log('Store these values in local/deployment secret storage. Do not commit them and do not prefix them with VITE_.');
